func decodeVector(t *testing.T, encoded string) []byte {
	t.Helper()
	data, err := decodeHexString(encoded)
	if err != nil {
		t.Fatalf("test vector is not valid hex: %v", err)
	}
	return data
}

func decodeHexString(encoded string) ([]byte, error) {
	return hex.DecodeString(encoded)
}
